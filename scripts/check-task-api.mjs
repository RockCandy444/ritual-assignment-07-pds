import assert from "node:assert/strict";
const origin = process.env.PDS_TEST_ORIGIN;
if (!origin || new URL(origin).hostname !== "127.0.0.1") throw new Error("Provide an isolated local test server.");
const request = async (path, method = "GET", body, headers = {}) => {
  const response = await fetch(origin + path, { method, headers: body ? { "Content-Type": "application/json", ...headers } : headers, body: body ? JSON.stringify(body) : undefined });
  return { status: response.status, data: await response.json() };
};
const planId = crypto.randomUUID();
const id = crypto.randomUUID();
const plan = { title: "[검증용] 할 일", startDate: "2026-09-27", endDate: "2026-10-06", priority: "normal", successCriteria: "검증", expectedMinutes: 30 };
assert.equal((await request("/api/plans", "POST", { id: planId, expectedVersion: 0, plan })).status, 201);
const task = { title: "처음 할 일", dueDate: "2026-09-30", priority: "normal", tags: ["어휘", "어휘"], expectedMinutes: 30 };
let result = await request("/api/tasks", "POST", { id, planId, task });
assert.equal(result.status, 201); assert.deepEqual(result.data.task.tags, ["어휘"]);
assert.equal((await request("/api/tasks", "POST", { id, planId, task })).status, 409);
const changed = { ...task, title: '<script>alert("검증")</script>', expectedMinutes: 40, priority: "high" };
result = await request("/api/tasks", "PATCH", { action: "edit", id, expectedVersion: 1, task: changed });
assert.equal(result.status, 200); assert.equal(result.data.task.title, changed.title); assert.equal(result.data.task.expectedMinutes, 40);
assert.equal((await request("/api/tasks", "PATCH", { action: "edit", id, expectedVersion: 1, task })).status, 409);
const completed = await Promise.all([request("/api/tasks", "PATCH", { action: "complete", id }), request("/api/tasks", "PATCH", { action: "complete", id })]);
assert.ok(completed.every(item => item.status === 200));
const afterComplete = (await request(`/api/tasks?planId=${planId}`)).data.tasks[0];
assert.equal(afterComplete.version, 3); assert.ok(afterComplete.completedAt);
result = await request("/api/tasks", "PATCH", { action: "reopen", id });
assert.equal(result.status, 200); assert.equal(result.data.task.completedAt, null); assert.equal(result.data.task.version, 4);
assert.equal((await request("/api/tasks", "PATCH", { action: "edit", id, expectedVersion: 4, task }, { Origin: "https://example.invalid" })).status, 400);
assert.equal((await request("/api/tasks", "POST", { id: crypto.randomUUID(), planId, task: { ...task, dueDate: "2026-02-30" } })).status, 400);
assert.equal((await request("/api/tasks", "DELETE", { id, expectedVersion: 3 })).status, 409);
assert.equal((await request("/api/tasks", "DELETE", { id, expectedVersion: 4 })).status, 200);
assert.deepEqual((await request(`/api/tasks?planId=${planId}`)).data.tasks, []);
console.log("Task API passed: create, duplicate guard, tags, edit, stale edit, concurrent completion, reopen, origin/date validation and delete.");
